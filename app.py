
import streamlit as st
import pandas as pd

from src.database import (
    init_db,
    create_session,
    log_event,
    save_decision,
    save_questionnaire
)

from src.review_data import TASK, FINDINGS
from src.review_ui import render_review
from src.analytics import load_analytics


# ============================================================
# 1. PAGE CONFIGURATION AND INITIALIZATION
# ============================================================

st.set_page_config(
    page_title="ReviewEase",
    page_icon="🧪",
    layout="wide"
)

init_db()

st.title("ReviewEase")
st.caption(
    "Human-AI Developer Review & Cognitive Workload Evaluation"
)

st.info(
    "Research prototype: findings are deterministic demo data, "
    "not generated by a live AI model."
)


# ============================================================
# 2. SESSION STATE INITIALIZATION
# ============================================================

DEFAULT_STATE = {
    "participant_code": "",
    "session_id": None,
    "started": False,
    "completed": False,
    "active_condition": None,
    "show_summary": False
}

for key, default in DEFAULT_STATE.items():
    if key not in st.session_state:
        st.session_state[key] = default


# ============================================================
# 3. SIDEBAR: STUDY SESSION CONFIGURATION
# ============================================================

with st.sidebar:

    st.header("Study session")

    participant = st.text_input(
        "Anonymous participant code",
        value=st.session_state.participant_code,
        help="Do not enter your name or email.",
        disabled=st.session_state.started
    )

    condition = st.selectbox(
        "Interface condition",
        [
            "Conventional review",
            "Progressive disclosure"
        ],
        disabled=st.session_state.started
    )

    # Keep participant code updated.
    if not st.session_state.started:
        st.session_state.participant_code = participant.strip()

    st.divider()

    if st.button(
        "View aggregate research analytics",
        use_container_width=True
    ):
        st.session_state.show_summary = True
        st.rerun()


# ============================================================
# 4. RESEARCH ANALYTICS DASHBOARD
# ============================================================

if st.session_state.show_summary:

    st.title("ReviewEase Research Analytics")

    st.caption(
        "Comparison of conventional review and progressive disclosure"
    )

    # Load research data.
    sessions, decisions, questionnaires, events = load_analytics()

    if sessions.empty:

        st.info("No research sessions recorded yet.")

    else:

        # Identify completed sessions.
        completed_sessions = sessions.dropna(
            subset=["completed_at"]
        ).copy()

        # ----------------------------------------------------
        # 4.1 OVERALL RESEARCH METRICS
        # ----------------------------------------------------

        total_sessions = len(sessions)

        total_completed = len(completed_sessions)

        total_participants = sessions[
            "participant_code"
        ].nunique()

        col1, col2, col3 = st.columns(3)

        col1.metric(
            "Total sessions",
            total_sessions
        )

        col2.metric(
            "Completed sessions",
            total_completed
        )

        col3.metric(
            "Unique participant codes",
            total_participants
        )

        st.divider()

        # ----------------------------------------------------
        # 4.2 DASHBOARD TABS
        # ----------------------------------------------------

        overview, workload, decisions_tab, interactions = st.tabs(
            [
                "Overview",
                "Workload & Trust",
                "Review Decisions",
                "Interactions"
            ]
        )

        # ====================================================
        # TAB 1: OVERVIEW
        # ====================================================

        with overview:

            st.subheader("Session overview")

            if not completed_sessions.empty:

                valid_durations = completed_sessions[
                    "duration_minutes"
                ].dropna()

                if not valid_durations.empty:

                    average_duration = valid_durations.mean()

                    st.metric(
                        "Average completion time",
                        f"{average_duration:.2f} minutes"
                    )

                else:

                    st.metric(
                        "Average completion time",
                        "N/A"
                    )

            else:

                st.info(
                    "Completion time will be available "
                    "after participants submit their questionnaires."
                )

            st.subheader("Recorded sessions")

            st.dataframe(
                sessions,
                use_container_width=True,
                hide_index=True
            )

            st.subheader("Completed sessions")

            if not completed_sessions.empty:

                st.dataframe(
                    completed_sessions,
                    use_container_width=True,
                    hide_index=True
                )

            else:

                st.info("No completed sessions yet.")

        # ====================================================
        # TAB 2: WORKLOAD AND TRUST
        # ====================================================

        with workload:

            st.subheader("Questionnaire comparison")

            if not questionnaires.empty:

                research_data = sessions[
                    ["session_id", "condition"]
                ].merge(
                    questionnaires,
                    on="session_id",
                    how="inner"
                )

                measures = [
                    "Mental demand",
                    "Effort",
                    "Frustration",
                    "Trust",
                    "Clarity"
                ]

                available_measures = [
                    column
                    for column in measures
                    if column in research_data.columns
                ]

                if available_measures:

                    # Calculate average responses per condition.
                    comparison = research_data.groupby(
                        "condition"
                    )[available_measures].mean().round(2)

                    # Count questionnaire responses per condition.
                    response_counts = research_data.groupby(
                        "condition"
                    ).size().rename("Responses")

                    comparison = comparison.join(
                        response_counts
                    )

                    st.write(
                        "Average questionnaire scores by interface condition."
                    )

                    st.dataframe(
                        comparison,
                        use_container_width=True
                    )

                    st.subheader("Visual comparison")

                    st.bar_chart(
                        comparison[available_measures].T
                    )

                    st.caption(
                        "Scores range from 1 to 7. These are exploratory "
                        "prototype questions, not a validated fatigue scale."
                    )

                    st.caption(
                        "Interpret results cautiously when participant "
                        "numbers are small or unequal."
                    )

                else:

                    st.info(
                        "No questionnaire measures are available."
                    )

            else:

                st.info(
                    "No questionnaire responses recorded yet."
                )

        # ====================================================
        # TAB 3: REVIEW DECISIONS
        # ====================================================

        with decisions_tab:

            st.subheader("Review decision distribution")

            if not decisions.empty:

                decision_data = decisions.merge(
                    sessions[
                        ["session_id", "condition"]
                    ],
                    on="session_id",
                    how="left"
                )

                decision_counts = pd.crosstab(
                    decision_data["condition"],
                    decision_data["decision"]
                )

                # Always show all three decision categories.
                expected_decisions = [
                    "Accept finding",
                    "Reject finding",
                    "Unsure"
                ]

                decision_counts = decision_counts.reindex(
                    columns=expected_decisions,
                    fill_value=0
                )

                st.write(
                    "Number of decisions recorded for each condition."
                )

                st.dataframe(
                    decision_counts,
                    use_container_width=True
                )

                st.subheader("Decision distribution chart")

                st.bar_chart(decision_counts)

                st.caption(
                    "Decision counts represent saved decisions, "
                    "not necessarily the number of unique findings "
                    "that were examined."
                )

            else:

                st.info(
                    "No review decisions recorded yet."
                )

        # ====================================================
        # TAB 4: INTERACTIONS
        # ====================================================

        with interactions:

            st.subheader("Recorded interaction events")

            if not events.empty:

                event_data = events.merge(
                    sessions[
                        ["session_id", "condition"]
                    ],
                    on="session_id",
                    how="left"
                )

                event_counts = pd.crosstab(
                    event_data["condition"],
                    event_data["event_type"]
                )

                st.write(
                    "Recorded event counts by interface condition."
                )

                st.dataframe(
                    event_counts,
                    use_container_width=True
                )

                st.subheader("Interaction event chart")

                st.bar_chart(
                    event_counts.T
                )

                st.caption(
                    "These are raw recorded event counts. "
                    "Expansion events should be checked for duplicate "
                    "logging caused by Streamlit reruns before "
                    "using them as research measurements."
                )

            else:

                st.info(
                    "No interaction events recorded yet."
                )

        # ====================================================
        # 4.3 RESEARCH DATA EXPORT
        # ====================================================

        st.divider()

        st.subheader("Export research data")

        st.caption(
            "Download the recorded datasets for further analysis."
        )

        export_col1, export_col2 = st.columns(2)

        export_col3, export_col4 = st.columns(2)

        with export_col1:

            st.download_button(
                label="Download session data",
                data=sessions.to_csv(
                    index=False
                ).encode("utf-8-sig"),
                file_name="reviewease_sessions.csv",
                mime="text/csv",
                use_container_width=True
            )

        with export_col2:

            st.download_button(
                label="Download review decisions",
                data=decisions.to_csv(
                    index=False
                ).encode("utf-8-sig"),
                file_name="reviewease_decisions.csv",
                mime="text/csv",
                use_container_width=True
            )

        with export_col3:

            st.download_button(
                label="Download questionnaires",
                data=questionnaires.to_csv(
                    index=False
                ).encode("utf-8-sig"),
                file_name="reviewease_questionnaires.csv",
                mime="text/csv",
                use_container_width=True
            )

        with export_col4:

            st.download_button(
                label="Download interaction events",
                data=events.to_csv(
                    index=False
                ).encode("utf-8-sig"),
                file_name="reviewease_interactions.csv",
                mime="text/csv",
                use_container_width=True
            )

    # --------------------------------------------------------
    # CLOSE ANALYTICS
    # --------------------------------------------------------

    st.divider()

    if st.button(
        "Close analytics",
        use_container_width=False
    ):

        st.session_state.show_summary = False
        st.rerun()

    # Prevent the review interface from appearing below analytics.
    st.stop()


# ============================================================
# 5. COMPLETED SESSION SCREEN
# ============================================================

if st.session_state.completed:

    st.success("Research session completed successfully.")

    st.write(
        "Your review decisions and questionnaire responses "
        "have been saved."
    )

    st.info(
        f"Participant code: {st.session_state.participant_code}"
    )

    st.info(
        f"Interface condition: {st.session_state.active_condition}"
    )

    if st.button(
        "Start a new session",
        type="primary"
    ):

        st.session_state.session_id = None
        st.session_state.started = False
        st.session_state.completed = False
        st.session_state.active_condition = None

        st.rerun()

    st.stop()


# ============================================================
# 6. REVIEW TASK
# ============================================================

st.subheader("Review task")

st.markdown(
    f"**Scenario:** {TASK['scenario']}"
)

st.write(
    TASK["instruction"]
)

with st.expander(
    "Code under review",
    expanded=True
):

    st.code(
        TASK["code"],
        language="python"
    )


# ============================================================
# 7. START A NEW REVIEW SESSION
# ============================================================

if not st.session_state.started:

    if st.button(
        "Start review",
        type="primary",
        disabled=not st.session_state.participant_code
    ):

        participant_code = st.session_state.participant_code

        active_condition = condition

        # Create a database session.
        sid = create_session(
            participant_code,
            active_condition
        )

        # Save session information.
        st.session_state.session_id = sid

        st.session_state.started = True

        st.session_state.active_condition = active_condition

        # Record the start event.
        log_event(
            sid,
            "review_started",
            {
                "condition": active_condition
            }
        )

        st.rerun()

    if not st.session_state.participant_code:

        st.caption(
            "Enter an anonymous participant code to begin."
        )


# ============================================================
# 8. ACTIVE REVIEW SESSION
# ============================================================

else:

    active_condition = st.session_state.active_condition

    session_id = st.session_state.session_id

    st.success(
        f"Active session · {active_condition}"
    )

    # Render the appropriate review interface.
    render_review(
        FINDINGS,
        active_condition,
        session_id,
        log_event,
        save_decision
    )

    st.divider()


    # ========================================================
    # 9. POST-TASK QUESTIONNAIRE
    # ========================================================

    st.subheader("Post-task questionnaire")

    st.caption(
        "Exploratory prototype questions, not a validated fatigue scale."
    )

    with st.form("questionnaire"):

        mental = st.slider(
            "How mentally demanding was this task?",
            min_value=1,
            max_value=7,
            value=4
        )

        effort = st.slider(
            "How much effort did you need?",
            min_value=1,
            max_value=7,
            value=4
        )

        frustration = st.slider(
            "How frustrated or overwhelmed did you feel?",
            min_value=1,
            max_value=7,
            value=4
        )

        trust = st.slider(
            "How much did you trust the findings?",
            min_value=1,
            max_value=7,
            value=4
        )

        clarity = st.slider(
            "How clear were the findings?",
            min_value=1,
            max_value=7,
            value=4
        )

        submitted = st.form_submit_button(
            "Submit questionnaire",
            type="primary"
        )

    # ========================================================
    # 10. SAVE QUESTIONNAIRE AND COMPLETE SESSION
    # ========================================================

    if submitted:

        responses = {
            "mental_demand": mental,
            "effort": effort,
            "frustration": frustration,
            "trust": trust,
            "clarity": clarity
        }

        # Save questionnaire responses.
        save_questionnaire(
            session_id,
            responses
        )

        # Record questionnaire submission.
        log_event(
            session_id,
            "questionnaire_submitted",
            {}
        )

        # Mark session as completed.
        st.session_state.completed = True

        st.rerun()
